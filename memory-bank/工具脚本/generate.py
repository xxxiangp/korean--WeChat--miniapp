def build_json_data(words, level, level_cn, description):
    """构建JSON数据结构"""
    data = {
        "level": level,
        "level_cn": level_cn,
        "description": description,
        "total": len(words),
        "words": []
    }
    for i, (korean, pron, pos, pos_cn, meaning) in enumerate(words, 1):
        data["words"].append({
            "id": i,
            "korean": korean,
            "pronunciation": pron,
            "pos": pos,
            "pos_cn": pos_cn,
            "meaning": meaning
        })
    return data


